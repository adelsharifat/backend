using System.Data;
using System.Text;
using System.Text.Json.Serialization;
using Microsoft.Data.SqlClient;

return await CmisCli.RunAsync(args);

internal static class Generator
{
    private const string Query = """
        SELECT s.name, tt.name, c.column_id, c.name, st.name, c.is_nullable
        FROM sys.table_types tt
        JOIN sys.schemas s ON s.schema_id = tt.schema_id
        JOIN sys.columns c ON c.object_id = tt.type_table_object_id
        JOIN sys.types st ON st.user_type_id = c.user_type_id
        WHERE tt.is_user_defined = 1
          AND (@schema IS NULL OR s.name = @schema)
          AND (@type IS NULL OR tt.name = @type)
        ORDER BY s.name, tt.name, c.column_id;
        """;

    public static async Task<int> RunAsync(string[] args, string? savedConnectionString = null)
    {
        var options = new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase);
        for (var i = 0; i < args.Length; i++)
        {
            if (args[i] is "--help" or "-h")
            {
                Help();
                return 0;
            }
            if (!args[i].StartsWith("--") || i + 1 >= args.Length)
            {
                Console.Error.WriteLine($"Invalid option: {args[i]}");
                Help();
                return 2;
            }
            options[args[i][2..]] = args[++i];
        }

        string? Option(string name, string? fallback = null) =>
            options.TryGetValue(name, out var value) ? value : fallback;

        var cs = Option("connection-string") ?? Environment.GetEnvironmentVariable("CMIS_CODEGEN_CONNECTION_STRING") ?? savedConnectionString;
        if (string.IsNullOrWhiteSpace(cs))
        {
            Console.Error.WriteLine("Run 'cmis connection set', set CMIS_CODEGEN_CONNECTION_STRING, or pass --connection-string.");
            return 2;
        }

        var output = Path.GetFullPath(Option("output", "Generated/TvpContracts.g.cs")!);
        var ns = Option("namespace", "CMIS.Generated.Tvp")!;
        var tables = new List<Tvp>();
        try
        {
            await using var connection = new SqlConnection(cs);
            await connection.OpenAsync();
            await using var command = new SqlCommand(Query, connection);
            command.Parameters.AddWithValue("@schema", (object?)Option("schema") ?? DBNull.Value);
            command.Parameters.AddWithValue("@type", (object?)Option("type") ?? DBNull.Value);
            await using var reader = await command.ExecuteReaderAsync();
            while (await reader.ReadAsync())
            {
                var schema = reader.GetString(0);
                var name = reader.GetString(1);
                var table = tables.FirstOrDefault(t => t.Schema == schema && t.Name == name);
                if (table is null)
                {
                    table = new Tvp(schema, name);
                    tables.Add(table);
                }
                table.Columns.Add(new Column(reader.GetString(3), reader.GetString(4), reader.GetBoolean(5)));
            }
            if (tables.Count == 0)
            {
                Console.Error.WriteLine("No matching user-defined table types found.");
                return 1;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(output)!);
            await File.WriteAllTextAsync(output, Generate(tables, ns), new UTF8Encoding(false));
            Console.WriteLine($"Generated {tables.Count} TVP contract(s): {output}");
            foreach (var table in tables)
                Console.WriteLine($"  {table.Schema}.{table.Name}: {table.Columns.Count} columns");
            return 0;
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Generation failed ({ex.GetType().Name}). Check the SQL connection, metadata permissions, and generator options.");
            return 1;
        }
    }

    private static string Generate(IEnumerable<Tvp> tables, string ns)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Generated by CodeGen. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Data;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();

        foreach (var table in tables)
        {
            var className = Id(table.Schema + "_" + table.Name);
            sb.AppendLine($"/// <summary>Generated from SQL table type {table.Schema}.{table.Name}.</summary>");
            sb.AppendLine($"public sealed class {className}");
            sb.AppendLine("{");
            foreach (var col in table.Columns)
            {
                sb.AppendLine($"    [JsonPropertyName({Lit(col.Name)})]");
                sb.AppendLine($"    public {Clr(col.SqlType, col.Nullable)} {Id(col.Name)} {{ get; set; }}");
                sb.AppendLine();
            }

            sb.AppendLine($"    public static DataTable ToDataTable(IEnumerable<{className}> items)");
            sb.AppendLine("    {");
            sb.AppendLine("        ArgumentNullException.ThrowIfNull(items);");
            sb.AppendLine($"        var table = new DataTable({Lit(table.Schema + "." + table.Name)});");
            foreach (var col in table.Columns)
                sb.AppendLine($"        table.Columns.Add(new DataColumn({Lit(col.Name)}, typeof({ClrBase(col.SqlType)})) {{ AllowDBNull = {(col.Nullable ? "true" : "false")} }});");
            sb.AppendLine("        foreach (var item in items)");
            sb.AppendLine("        {");
            sb.AppendLine("            ArgumentNullException.ThrowIfNull(item);");
            sb.AppendLine("            var row = table.NewRow();");
            foreach (var col in table.Columns)
                sb.AppendLine($"            row[{Lit(col.Name)}] = (object?)item.{Id(col.Name)} ?? DBNull.Value;");
            sb.AppendLine("            table.Rows.Add(row);");
            sb.AppendLine("        }");
            sb.AppendLine("        return table;");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();
        }
        return sb.ToString();
    }

    private static string Clr(string sql, bool nullable)
    {
        var type = ClrBase(sql);
        if (!nullable) return type;
        return type is "string" or "byte[]" ? type + "?" : type + "?";
    }

    private static string ClrBase(string sql) => sql.ToLowerInvariant() switch
    {
        "bit" => "bool", "tinyint" => "byte", "smallint" => "short", "int" => "int",
        "bigint" => "long", "real" => "float", "float" => "double",
        "decimal" or "numeric" or "money" or "smallmoney" => "decimal",
        "uniqueidentifier" => "Guid", "date" or "datetime" or "datetime2" or "smalldatetime" => "DateTime",
        "datetimeoffset" => "DateTimeOffset", "time" => "TimeSpan",
        "binary" or "varbinary" or "image" or "timestamp" or "rowversion" => "byte[]",
        "char" or "varchar" or "nchar" or "nvarchar" or "text" or "ntext" or "xml" => "string",
        _ => throw new NotSupportedException($"Unsupported SQL type '{sql}'. Add an explicit mapping before generating.")
    };

    private static string Id(string value)
    {
        var id = System.Text.RegularExpressions.Regex.Replace(value, "[^A-Za-z0-9_]", "_");
        if (id.Length == 0) id = "Generated";
        if (char.IsDigit(id[0])) id = "_" + id;
        if (Keywords.Contains(id)) id = "@" + id;
        return id;
    }

    private static string Lit(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const",
        "continue","decimal","default","delegate","do","double","else","enum","event","explicit","extern",
        "false","finally","fixed","float","for","foreach","goto","if","implicit","in","int","interface",
        "internal","is","lock","long","namespace","new","null","object","operator","out","override","params",
        "private","protected","public","readonly","ref","return","sbyte","sealed","short","sizeof","stackalloc",
        "static","string","struct","switch","this","throw","true","try","typeof","uint","ulong","unchecked",
        "unsafe","ushort","using","virtual","void","volatile","while"
    };

    private static void Help() => Console.WriteLine("""
        CMIS CLI - generate strongly typed C# contracts and DataTable mappers from SQL Server TVPs.
        Usage: cmis generate tvp [--connection-string "<connection string>"] [--schema PIPE] [--type LinesType]
                                 [--namespace CMIS.Generated.Tvp] [--output Generated/TvpContracts.g.cs]
        Connection string precedence: --connection-string, CMIS_CODEGEN_CONNECTION_STRING, then the encrypted value saved by 'cmis connection set'.
        """);

    private sealed class Tvp(string schema, string name)
    {
        public string Schema { get; } = schema;
        public string Name { get; } = name;
        public List<Column> Columns { get; } = [];
    }
    private sealed record Column(string Name, string SqlType, bool Nullable);
}
